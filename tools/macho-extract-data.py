"""Cut named data objects out of a Mach-O file and write them as assembler source (the tables of a rebuilt file that are data, not code).

usage: macho-extract-data.py IMAGE OUT.S SYMBOL...
IMAGE   the original file (found under the original package's root by the build; nothing of it is kept in the repository).
OUT.S   assembler source: for each SYMBOL, a private-extern symbol of the same name and section, aligned like the original, holding the same bytes
        (the bytes go to OUT.S.d/SYMBOL.bin and are included with .incbin, which keeps the source small).
SYMBOL  name as in the symbol table of IMAGE; its size is the distance to the next symbol of the same section (or the section's end).
The objects must not hold pointers (a table of pointers is a C initialiser that names the symbols).  Run by tools/build-macho.py for the
`generate` key of a target.conf, in the reef-build image or anywhere with Python 3."""
import os, struct, sys

def read(path):
    b = open(path, 'rb').read()
    magic, cpu, sub, ftype, ncmds, sizeofcmds, flags = struct.unpack_from('<IiiIIII', b, 0)
    if magic != 0xfeedfacf: raise SystemExit(path + ': not a 64-bit Mach-O file')
    sections, symoff, nsyms, stroff = [], 0, 0, 0
    off = 32
    for _ in range(ncmds):
        cmd, size = struct.unpack_from('<II', b, off)
        if cmd == 0x19:
            nsects = struct.unpack_from('<I', b, off + 64)[0]
            so = off + 72
            for _ in range(nsects):
                name = b[so:so + 16].split(b'\0')[0].decode(); seg = b[so + 16:so + 32].split(b'\0')[0].decode()
                addr, ssize, foff, align = struct.unpack_from('<QQII', b, so + 32)
                sections.append(dict(seg=seg, name=name, addr=addr, size=ssize, off=foff, align=align))
                so += 80
        elif cmd == 2:
            symoff, nsyms, stroff = struct.unpack_from('<III', b, off + 8)
        off += size
    syms = []
    for i in range(nsyms):
        strx, typ, sect, desc, value = struct.unpack_from('<IBBHQ', b, symoff + 16 * i)
        if typ & 0xe0 or (typ & 0xe) != 0xe or sect == 0: continue          # stabs, undefined, absolute
        end = b.index(b'\0', stroff + strx)
        syms.append((b[stroff + strx:end].decode(), value, sect - 1))
    return b, sections, syms

def main():
    if len(sys.argv) < 4: sys.exit(__doc__)
    image, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]
    b, sections, syms = read(image)
    bysect = {}
    for name, value, sect in syms: bysect.setdefault(sect, []).append((value, name))
    for v in bysect.values(): v.sort()
    byname = {name: (value, sect) for name, value, sect in syms}
    directory = out + '.d'
    os.makedirs(directory, exist_ok=True)
    lines = ['// Generated by tools/macho-extract-data.py from %s: do not edit.' % os.path.basename(image)]
    for name in names:
        if name not in byname: raise SystemExit('%s: no symbol %s' % (image, name))
        value, sect = byname[name]
        s = sections[sect]
        later = [v for v, n in bysect[sect] if v > value]
        end = min(later) if later else s['addr'] + s['size']
        data = b[s['off'] + value - s['addr']:s['off'] + end - s['addr']]
        # the table's own alignment: that of its address, up to the section's
        align = 0
        while align < s['align'] and value % (2 << align) == 0: align += 1
        path = os.path.abspath(os.path.join(directory, name + '.bin'))
        open(path, 'wb').write(data)
        lines += ['.section %s,%s' % (s['seg'], s['name']), '.p2align %d' % align, '.private_extern %s' % name, '%s:' % name, '.incbin "%s"' % path]
    open(out, 'w').write('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main()
