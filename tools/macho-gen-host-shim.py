"""Write the source folder of a host shim for a library the original package lacks: every function that macOS exports is a jump through a table that the
host's library fills in when the shim is loaded (as macho/usr/lib/libexpat.1 does); the data symbols are zeroed variables of the shim.
usage: macho-gen-host-shim.py OFFSETS.txt FOLDER INSTALL VERSION COMPAT HOSTLIB...
OFFSETS.txt  lines `OFFSET SYMBOL` as `dyld_info -exports` prints them for the library in the cache of macOS; an offset above 0x10000000 is data, below it code
HOSTLIB      the Linux libraries (sonames) that hold the functions, tried in this order
Run it again to regenerate; the files carry a note that they are generated."""
import sys, os
offsets, folder, install, version, compat, *hosts = sys.argv[1:]
funcs, data = [], []
for line in open(offsets):
    off, sym = line.split()
    (data if int(off, 16) > 0x10000000 else funcs).append(sym[1:])
funcs.sort(); data.sort()
os.makedirs(folder, exist_ok=True)
lib = os.path.basename(install).split('.')[0]
hdr = '// SPDX-FileCopyrightText: 2026 Alexandru Balan\n// SPDX-License-Identifier: BSD-2-Clause\n//\n// Generated by tools/macho-gen-host-shim.py from the export list of %s on macOS.\n' % os.path.basename(install)
open(os.path.join(folder, 'symbols.h'), 'w').write(hdr + '\n#define SYMBOLS(X) \\\n' + ' \\\n'.join('    X(%d, %s)' % (i, n) for i, n in enumerate(funcs)) + '\n')
open(os.path.join(folder, 'trampolines.S'), 'w').write(hdr + '// One jump through the slot table for every function; the data symbols are variables.\n\n#include "symbols.h"\n\n#define TRAMPOLINE(i, name) \\\n    .globl _##name ;\\\n    .p2align 3 ;\\\n    _##name: ;\\\n    jmpq *_reef_%s_slots + i * 8(%%rip) ;\n\n.text\nSYMBOLS(TRAMPOLINE)\n\n.data\n' % lib
    + ''.join('.globl _%s\n.p2align 4\n_%s: .space 64\n' % (d, d) for d in data))
open(os.path.join(folder, lib + '.c'), 'w').write(hdr + '''
#include "symbols.h"

extern void *reef_host_symbol(const char *library, const char *name);
extern void reef_bridge_missing(void);

enum {
#define COUNT(i, name) +1
    SYMBOL_COUNT = 0 SYMBOLS(COUNT)
#undef COUNT
};

__attribute__((visibility("hidden"))) void *reef_%s_slots[SYMBOL_COUNT];

static const char *const names[] = {
#define NAME(i, name) #name,
    SYMBOLS(NAME)
};
static const char *const hosts[] = { %s, 0 };

__attribute__((constructor)) static void resolve(void)
{
    for (int i = 0; i < SYMBOL_COUNT; i++) {
        void *function = 0;
        for (int h = 0; hosts[h] && !function; h++)
            function = reef_host_symbol(hosts[h], names[i]);
        reef_%s_slots[i] = function ? function : (void *)reef_bridge_missing;
    }
}
''' % (lib, ', '.join('"%s"' % h for h in hosts), lib))
open(os.path.join(folder, 'target.conf'), 'w').write('''# %s: the functions of macOS' %s through the host's %s (generated by tools/macho-gen-host-shim.py).
install = %s
id = /%s
version = %s
compat = %s
sources = trampolines.S %s.c
cflags = -fcommon
''' % (os.path.basename(install), lib, ' and '.join(hosts), install, install, version, compat, lib))
print('%d functions, %d data symbols' % (len(funcs), len(data)))
